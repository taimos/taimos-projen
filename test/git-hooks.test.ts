import { Testing, typescript } from 'projen';
import { GitHooks, MonorepoProject } from '../src';

function synth(options = {}, withSub = true) {
  const project = new MonorepoProject({ name: 'test-monorepo', defaultReleaseBranch: 'main', gitHooks: true, gitHooksOptions: options });
  if (withSub) {
    new typescript.TypeScriptProject({
      parent: project, outdir: 'packages/backend', name: 'backend', defaultReleaseBranch: 'main',
    });
  }
  return { project, out: Testing.synth(project) as Record<string, any> };
}

describe('GitHooks (ADR-0013)', () => {
  test('emits lefthook.yml with drift, gitleaks, and per-package jobs', () => {
    const { out } = synth();
    const y = out['lefthook.yml'];
    expect(y).toContain('piped: true');
    expect(y).toContain('name: projen-drift');
    expect(y).toContain('gitleaks git --staged --redact --no-banner');
    expect(y).toContain('root: packages/backend/');
    expect(y).toContain('pnpm exec eslint {staged_files}');
    expect(y).toContain('pnpm exec tsc --noEmit');
    expect(y).toContain('name: conventional-first-commit');
  });

  test('adds prepare script and pinned lefthook devDependency', () => {
    const { out } = synth();
    expect(out['package.json'].scripts.prepare).toBe('lefthook install');
    expect(out['package.json'].devDependencies.lefthook).toBe('1.11.13');
  });

  test('commit-msg script uses the PR title types and default branch', () => {
    const { out } = synth({ commitTypes: ['feat', 'fix'] });
    const sh = out['.lefthook/commit-msg.sh'];
    expect(sh).toContain('(feat|fix)');
    expect(sh).toContain('base="main"');
    expect(sh).toContain('rev-list --count');
  });

  test('plain frontend packages use their own scripts', () => {
    const { out } = synth({ packages: [{ path: 'packages/web' }] }, false);
    const y = out['lefthook.yml'];
    expect(y).toContain('name: lint-web');
    expect(y).toContain('run: pnpm run typecheck');
  });

  test('checks can be switched off', () => {
    const { out } = synth({ gitleaks: false, projenDrift: false }, false);
    expect(out['lefthook.yml']).not.toContain('gitleaks git');
    expect(out['.lefthook/projen-drift.sh']).toBeUndefined();
  });

  test('not generated by default', () => {
    const project = new MonorepoProject({ name: 'test-monorepo', defaultReleaseBranch: 'main' });
    const out = Testing.synth(project) as Record<string, any>;
    expect(out['lefthook.yml']).toBeUndefined();
    expect(project.gitHooks).toBeUndefined();
    expect(GitHooks).toBeDefined();
  });
});
